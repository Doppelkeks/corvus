function parsePath(source) {
    if (!source) return Object.freeze([]);
    return Object.freeze(source.split("|").map((path) =>
        Object.freeze(path.trim().split(/\s+/).map((point) => {
            const [x, y] = point.split(",").map(Number);
            return Object.freeze({ x: x / 10, y: y / 10 });
        }))));
}

const STROKE_PATHS = Object.freeze(Object.fromEntries(
    Object.entries(STROKE_SOURCE).map(([character, source]) => [
        character,
        parsePath(source)
    ])
));

export function glyphStrokePaths(character) {
    return STROKE_PATHS[character] ?? null;
}
